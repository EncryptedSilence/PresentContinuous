#!/usr/bin/env python3
"""Emit the S-box functions of the full-round FPGA cores (fpga/rtl/*_sbox.vh).

The tables are parsed from the C reference sources, which the host KAT suite verifies, so
the RTL cannot carry a transcription error of its own: aes_sbox[] in src/aes/aes128_ref.c
and SB[] in src/qalqan/qalqan.c (СТ РК 4009-2025)."""
import re
import sys
from pathlib import Path

CA = Path(__file__).resolve().parents[2]


def table(path: Path, name: str) -> list[int]:
    src = path.read_text()
    m = re.search(re.escape(name) + r"\s*\[256\]\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        sys.exit(f"{path}: table {name} not found")
    vals = [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]{2}", m.group(1))]
    if len(vals) != 256 or sorted(vals) != list(range(256)):
        sys.exit(f"{path}: {name} is not a 256-entry permutation")
    return vals


def emit(fn: str, vals: list[int], src: str) -> str:
    lines = [f"// AUTO-GENERATED by fpga/tools/gen_tables.py from {src}. Do not edit.",
             f"function [7:0] {fn};", "  input [7:0] x;", "  begin", "    case (x)"]
    lines += [f"      8'h{i:02x}: {fn} = 8'h{v:02x};" for i, v in enumerate(vals)]
    lines += ["    endcase", "  end", "endfunction", ""]
    return "\n".join(lines)


def main() -> None:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else CA / "fpga" / "rtl"
    out.mkdir(parents=True, exist_ok=True)
    aes = table(CA / "src/aes/aes128_ref.c", "aes_sbox")
    if aes[0] != 0x63 or aes[0x53] != 0xED:
        sys.exit("aes_sbox: FIPS-197 spot check failed")
    (out / "aes_sbox.vh").write_text(emit("aes_sbox", aes, "src/aes/aes128_ref.c aes_sbox[]"))
    q = table(CA / "src/qalqan/qalqan.c", "SB")
    (out / "qalqan_sbox.vh").write_text(emit("qalqan_sbox", q, "src/qalqan/qalqan.c SB[]"))
    print(f"wrote {out}/aes_sbox.vh, {out}/qalqan_sbox.vh")


if __name__ == "__main__":
    main()
