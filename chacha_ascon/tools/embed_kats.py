#!/usr/bin/env python3
"""Embed the KAT files into a C source so the same test binary runs unchanged on
the host, under qemu-arm, and on a bare-metal target with no file system."""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = [("kat_chacha20_long", "chacha20_long.txt"),
         ("kat_ascon_long", "ascon_aead128_long.txt"),
         ("kat_ascon_lwc", "LWC_AEAD_KAT_128_128.txt")]
out = sys.argv[1]
with open(out, "w") as f:
    f.write("/* generated by chacha_ascon/tools/embed_kats.py -- do not edit */\n")
    for sym, fn in FILES:
        data = open(os.path.join(ROOT, "kat", fn), "rb").read()
        f.write("const unsigned long %s_len = %d;\n" % (sym, len(data)))
        f.write("const unsigned char %s[] = {\n" % sym)
        for i in range(0, len(data), 24):
            f.write(",".join(str(b) for b in data[i:i + 24]) + ",\n")
        f.write("0};\n")
